// 写命令
static void OLED_WriteCmd(uint8_t cmd)
{
    uint8_t buf[2] = {0x00, cmd};
    HAL_I2C_Master_Transmit(&hi2c1, OLED_ADDR, buf, 2, 100);
}

// 写数据
static void OLED_WriteData(uint8_t dat)
{
    uint8_t buf[2] = {0x40, dat};
    HAL_I2C_Master_Transmit(&hi2c1, OLED_ADDR, buf, 2, 100);
}

// 初始化OLED
void OLED_Init(void)
{
    HAL_Delay(100);
    
    OLED_WriteCmd(0xAE); // Display OFF
    
    OLED_WriteCmd(0x20); // Set Memory Addressing Mode
    OLED_WriteCmd(0x00); // Horizontal Addressing Mode
    
    OLED_WriteCmd(0xB0); // Set Page Start Address
    OLED_WriteCmd(0xC8); // COM Output Scan Direction
    OLED_WriteCmd(0x00); // Low Column Start Address
    OLED_WriteCmd(0x10); // High Column Start Address
    OLED_WriteCmd(0x40); // Set Display Start Line
    
    OLED_WriteCmd(0x81); // Set Contrast Control
    OLED_WriteCmd(0xFF); // Max contrast
    
    OLED_WriteCmd(0xA1); // Segment Re-map
    OLED_WriteCmd(0xA6); // Normal Display
    OLED_WriteCmd(0xA8); // Multiplex Ratio
    OLED_WriteCmd(0x3F); // 64 lines
    OLED_WriteCmd(0xA4); // Output follows RAM
    OLED_WriteCmd(0xD3); // Display Offset
    OLED_WriteCmd(0x00);
    OLED_WriteCmd(0xD5); // Display Clock Divide
    OLED_WriteCmd(0xF0);
    OLED_WriteCmd(0xD9); // Pre-charge Period
    OLED_WriteCmd(0x22);
    OLED_WriteCmd(0xDA); // COM Pins Configuration
    OLED_WriteCmd(0x12);
    OLED_WriteCmd(0xDB); // VCOMH Deselect Level
    OLED_WriteCmd(0x20);
    OLED_WriteCmd(0x8D); // Charge Pump
    OLED_WriteCmd(0x14);
    OLED_WriteCmd(0xAF); // Display ON
    
    OLED_Clear();
}

// 清屏
void OLED_Clear(void)
{
    memset(OLED_Buffer, 0x00, sizeof(OLED_Buffer));
    OLED_Refresh();
}

// 刷新显存到OLED
void OLED_Refresh(void)
{
    for(uint8_t page = 0; page < 8; page++)
    {
        OLED_WriteCmd(0xB0 + page);
        OLED_WriteCmd(0x00);
        OLED_WriteCmd(0x10);
        
        for(uint8_t col = 0; col < 128; col++)
        {
            OLED_WriteData(OLED_Buffer[col][page]);
        }
    }
}

// 显示字符串（只写入显存，不自动刷新）
void OLED_ShowString(uint8_t x, uint8_t y, const char *str)
{
    while(*str && x <= 122)
    {
        uint8_t idx = *str - ' ';
        if(idx < 64)
        {
            for(uint8_t i = 0; i < 6; i++)
            {
                OLED_Buffer[x + i][y] = Font6x8[idx][i];
            }
        }
        x += 6;
        str++;
    }
}

// 显示数字（只写入显存，不自动刷新）
void OLED_ShowNum(uint8_t x, uint8_t y, uint32_t num, uint8_t len)
{
    char buf[12];
    uint8_t i;
    for(i = len; i > 0; i--)
    {
        buf[i-1] = '0' + (num % 10);
        num /= 10;
    }
    buf[len] = '\0';
    OLED_ShowString(x, y, buf);
}

// 显示浮点数（只写入显存，不自动刷新）
void OLED_ShowFloat(uint8_t x, uint8_t y, float num, uint8_t intLen, uint8_t decLen)
{
    char buf[20];
    snprintf(buf, sizeof(buf), "%*.*f", intLen + decLen + 1, decLen, num);
    OLED_ShowString(x, y, buf);
}